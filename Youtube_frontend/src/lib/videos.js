export const DEFAULT_VIDEO_ID = VIDEOS[0].id;

export function getVideo(videoId) {
  return VIDEOS.find((video) => video.id === videoId) || VIDEOS[0];
}

export function getVideoId(video) {
  return video?.videoId || video?.id || '';
}

export function getVideoThumbnail(video) {
  return video?.thumbnail || video?.thumbnailUrl || video?.poster || '';
}

export function getVideoGradient(video) {
  const id = getVideoId(video);
  const gradient = VIDEOS.find((item) => item.id === id)?.gradient;
  return gradient || 'linear-gradient(135deg, #272727, #0f0f0f)';
}
